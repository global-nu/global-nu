#!/usr/bin/env python3
"""Build the word list Literature search uses to tell topics from surnames.

    ./.venv/bin/python3 -I tools/search_vocab.py [--fetch]

--fetch downloads arXiv abstracts about neutrinos (hep-ph, hep-ex, astro-ph,
nucl-ex) through the arXiv API into var/search-vocab/raw/ (one Atom file per
page, 3 s apart as the API asks). Without it, the cached pages are reused.

From titles and abstracts it keeps
  * words written in lower case at least MIN_LOWER times: the vocabulary a
    query about physics is made of ("endpoint", "tritium", "ultralight");
  * acronyms and mixed-case units ("keV", "CNO", "MSW") seen as often;
  * words written with a capital in the middle of a sentence at least
    MIN_CAP times and never in lower case: eponyms and proper topics
    ("Hubble", "Lorentz", "Earth"). Tokens are split on white space only, so
    a name inside "Mikheyev-Smirnov-Wolfenstein" stays inside its compound
    and does not make "Smirnov" a topic.
Author names are not in abstracts, so neither list contains them.

The lists are written between the VOCAB markers in site-src/assets/js/search.js,
so the page (and the offline tests) need no extra request.
"""

from __future__ import annotations

import collections
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "var/search-vocab/raw"
JS = ROOT / "site-src/assets/js/search.js"
QUERY = ("(cat:hep-ph OR cat:hep-ex OR cat:astro-ph.CO OR cat:astro-ph.HE OR cat:nucl-ex) "
         "AND (abs:neutrino OR abs:neutrinos)")
PAGES, PER = 20, 200
MIN_LOWER, MIN_CAP = 2, 3


def fetch() -> None:
    RAW.mkdir(parents=True, exist_ok=True)
    for p in range(PAGES):
        out = RAW / f"page{p:02d}.xml"
        if out.exists() and out.stat().st_size > 1000:
            continue
        q = urllib.parse.urlencode({"search_query": QUERY, "start": p * PER, "max_results": PER,
                                    "sortBy": "submittedDate", "sortOrder": "descending"})
        req = urllib.request.Request("https://export.arxiv.org/api/query?" + q,
                                     headers={"User-Agent": "global-nu search vocabulary"})
        with urllib.request.urlopen(req, timeout=60) as r:
            data = r.read()
        if b"<entry>" not in data:
            sys.exit(f"page {p}: no entries — stopping")
        out.write_bytes(data)
        print(f"  page {p}: {len(data)} bytes")
        time.sleep(3)


def texts() -> list[str]:
    out = []
    for f in sorted(RAW.glob("page*.xml")):
        s = f.read_text(encoding="utf-8", errors="replace")
        for e in re.findall(r"<entry>(.*?)</entry>", s, re.S):
            for tag in ("title", "summary"):
                m = re.search(rf"<{tag}[^>]*>(.*?)</{tag}>", e, re.S)
                if m:
                    out.append(re.sub(r"\$[^$]*\$", " ", m.group(1)))
    return out


def build() -> tuple[list[str], list[str]]:
    low, cap, acro = collections.Counter(), collections.Counter(), collections.Counter()
    for t in texts():
        for sent in re.split(r"(?<=[.!?:])\s+", t):
            toks = sent.split()
            for i, tok in enumerate(toks):
                w = tok.strip(".,;:()[]{}\"'`")
                if not re.fullmatch(r"[A-Za-z]{2,}", w):
                    continue
                if not w.islower() and not re.fullmatch(r"[A-Z][a-z]+", w):
                    acro[w.lower()] += 1        # keV, CNO, GeV, MSW: a topic
                    continue
                if len(w) < 3:
                    continue
                if w.islower():
                    low[w] += 1
                elif i > 0 and re.fullmatch(r"[A-Z][a-z]{2,}", w):
                    cap[w.lower()] += 1
    lower = sorted(set(w for w, n in low.items() if n >= MIN_LOWER) |
                   set(w for w, n in acro.items() if n >= MIN_LOWER and len(w) >= 2))
    eponyms = sorted(w for w, n in cap.items() if n >= MIN_CAP and low[w] == 0)
    return lower, eponyms


def main() -> None:
    if "--fetch" in sys.argv:
        fetch()
    lower, eponyms = build()
    block = ("/* VOCAB:BEGIN — generated by tools/search_vocab.py from arXiv abstracts; do not edit */\n"
             f'  var VOCAB_LOWER = new Set("{" ".join(lower)}".split(" "));\n'
             f'  var VOCAB_EPONYM = new Set("{" ".join(eponyms)}".split(" "));\n'
             "  /* VOCAB:END */")
    s = JS.read_text(encoding="utf-8")
    new = re.sub(r"/\* VOCAB:BEGIN.*?/\* VOCAB:END \*/", lambda m: block, s, flags=re.S)
    if new == s and "VOCAB:BEGIN" not in s:
        sys.exit("markers not found in search.js")
    if new != s:
        JS.write_text(new, encoding="utf-8")
    print(f"{len(texts())} texts · {len(lower)} lower-case words · {len(eponyms)} eponyms "
          f"· {len(block) // 1024} KB")


if __name__ == "__main__":
    main()
